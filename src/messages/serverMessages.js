/** Tham số là tên vai trò (ví dụ "Trainer") được đổi sang nhãn tiếng Việt; giá trị khác giữ nguyên. */
function formatArgument(value) {
    const text = String(value ?? '');
    return isKnownRole(text) ? getRoleLabel(text) : text;
}

/**
 * Dịch mã thông điệp Backend sang tiếng Việt.
 * @param code MessageKey từ Backend (messageKey / messageCode).
 * @param args Tham số theo thứ tự {0}, {1}…; thiếu tham số thì để trống thay vì hiện ký hiệu.
 * @param fallback Câu hiển thị khi mã không có trong catalog (mã mới hoặc dữ liệu cũ).
 */
export function serverMessage(code, args = [], fallback = null) {
    if (typeof code !== 'string' || !Object.hasOwn(SERVER_MESSAGES, code)) return fallback;
    const values = Array.isArray(args) ? args : [];
    return SERVER_MESSAGES[code].replace(/\{(\d+)\}/g, (_, index) => formatArgument(values[Number(index)]));
}
